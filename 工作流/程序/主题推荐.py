def 抽取意图(输入):
    """返回 {维度: 取值}，每维度最多一个。"""
    意图 = {}
    for 维, 组s in 意图词典.items():
        for 词s, 取值 in 组s:
            if any(w in 输入 for w in 词s):
                意图[维] = 取值
                break
    # 深浅：先看否定，再看肯定
    for 否 in 否定词:
        for 底, 词s in 深浅意图.items():
            if 否 in 输入 and any(w in 输入 for w in 词s):
                意图["深浅否定"] = 底
    if "深浅否定" not in 意图:
        for 底, 词s in 深浅意图.items():
            if any(w in 输入 for w in 词s):
                意图["深浅"] = 底
                break
    # 题材强暗示默认气质
    if "气质" not in 意图 and 意图.get("题材") in 题材默认气质:
        意图["气质"] = 题材默认气质[意图["题材"]]
    return 意图


