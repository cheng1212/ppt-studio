def 标签命中(映射表, tag, 取值):
    """标签映射值可为单值或集合，判断意图取值是否命中。"""
    m = 映射表.get(tag, tag)
    if isinstance(m, (set, list, tuple)):
        return 取值 in m
    return m == 取值

维度权重 = {"题材": 5, "受众": 3, "场地": 4, "内容类型": 4, "气质": 3, "深浅": 3}



def 读主题卡():
    out = []
    d = os.path.join(LIB_DIR, "主题", "卡片")
    for f in sorted(os.listdir(d)):
        if not (f.startswith("主题卡-") and f.endswith(".md")):
            continue
        name = f[len("主题卡-"):-len(".md")]
        txt = io.open(os.path.join(d, f), encoding="utf-8").read()
        m = re.search(r"## 匹配标签[\s\S]*?\n((?:- (?:深浅|行业|气质|场景|关键词):.*\n)+)", txt)
        if not m:
            continue
        tags = {}
        for line in m.group(1).strip().split("\n"):
            mm = re.match(r"- (深浅|行业|气质|场景|关键词):\s*(.*)", line)
            if mm:
                tags[mm.group(1)] = [x.strip() for x in re.split(r"[、,，]", mm.group(2)) if x.strip()]
        m1 = re.search(r"## 一句话\n+(.*?)(?:\n## |\Z)", txt, re.S)
        一句话 = m1.group(1).strip().split("\n")[0] if m1 else ""
        m2 = re.search(r"- 状态:\s*(.*)", txt)
        状态 = m2.group(1).strip() if m2 else ""
        out.append({"name": name, "tags": tags, "一句话": 一句话, "状态": 状态})
    return out


def 推荐(输入, top=3):
    """v2：先抽取意图（题材/受众/场地/内容类型/气质/深浅），再按维度匹配。
    每维度只计一次分；否定词直接否决对应深浅。返回 (结果, 是否命中, 意图)。"""
    意图 = 抽取意图(输入)
    主题s = 读主题卡()
    结果 = []
    for th in 主题s:
        tags = th["tags"]
        分 = 0
        理由 = []
        # 题材：主题行业标签 → 意图题材（一对多，见 行业命中题材）
        题材 = 意图.get("题材")
        if 题材:
            for tag in tags.get("行业", []):
                if 题材 in 行业命中题材.get(tag, {tag}):
                    分 += 维度权重["题材"]
                    理由.append("题材对上「%s」" % 题材)
                    break
        # 受众/场地/气质：标签转意图后比对（支持一对多）
        for 维, 标签维 in (("受众", "场景"), ("场地", "场景"), ("气质", "气质")):
            取值 = 意图.get(维)
            if not 取值:
                continue
            for tag in tags.get(标签维, []):
                if 标签命中(标签到意图.get(标签维, {}), tag, 取值):
                    分 += 维度权重[维]
                    理由.append("%s对上「%s」" % (维, 取值))
                    break
        内容类型 = 意图.get("内容类型")
        if 内容类型:
            for kw in tags.get("关键词", []):
                if kw in ("数据", "报告", "战报") and 内容类型 == "数据报告":
                    分 += 维度权重["内容类型"]
                    理由.append("内容类型对上「数据报告」")
                    break
                if kw in ("课件", "教学") and 内容类型 == "课件":
                    分 += 维度权重["内容类型"]
                    理由.append("内容类型对上「课件」")
                    break
        # 深浅
        深浅 = 意图.get("深浅")
        if 深浅 and 深浅 in tags.get("深浅", []):
            分 += 维度权重["深浅"]
            理由.append("深浅对上（%s）" % 深浅)
        # 否定：一票否决
        否 = 意图.get("深浅否定")
        if 否 and 否 in tags.get("深浅", []):
            分 = -100
            理由.append("已排除（用户不要%s）" % 否)
        if "草案" in th["状态"]:
            理由.append("（草案，样张待拍板）")
        结果.append((分, th, 理由))
    结果.sort(key=lambda x: -x[0])
    if 结果 and 结果[0][0] <= 0:
        浅 = [r for r in 结果 if "浅底" in r[1]["tags"].get("深浅", []) and r[0] > -100]
        深 = [r for r in 结果 if "深底" in r[1]["tags"].get("深浅", []) and r[0] > -100]
        挑 = []
        for r in 浅[:2]:
            挑.append(r)
        for r in 深[:1]:
            挑.append(r)
        for r in 结果:
            if r not in 挑 and len(挑) < top and r[0] > -100:
                挑.append(r)
        return [(0, th, ["无明确匹配，给你风格迥异的三个备选"]) for _, th, _ in 挑[:top]], False, 意图
    return [(s, th, r) for s, th, r in 结果[:top] if s > -100], True, 意图


