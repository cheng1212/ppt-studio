# -*- coding: utf-8 -*-
"""示例-图表14：生成 15 张图表 PNG（G11 双面板需 2 张）。"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "程序"))
from 图表 import bar, line, pie, waterfall, combo, dumbbell, pareto, stacked, multiples, bullet_rows

T = "redox"
S = os.path.join(os.path.dirname(os.path.abspath(__file__)), "素材")

# G1 rail：渠道销量
bar(T, {"直营店": 48, "经销商": 36, "电商": 22, "大客户": 14}, 强调="直营店",
    单位="万辆", 输出=os.path.join(S, "g1.png"))
# G2 multiples：四区域月度趋势
multiples(T, {"华东": [12, 18, 25, 31], "华南": [10, 14, 19, 24],
              "华北": [8, 11, 15, 20], "西南": [5, 8, 12, 16]},
          ["Q1", "Q2", "Q3", "Q4"], 高亮="华东", 单位="万辆", 宽=15, 高=7,
          输出=os.path.join(S, "g2.png"))
# G3 waterfall：利润桥
waterfall(T, [("期初", 100), ("规模效应", 45), ("价格战", -20), ("成本优化", 30), ("期末", 0)],
          单位="亿元", 宽=15, 高=6, 输出=os.path.join(S, "g3.png"))
# G4 combo：销量+渗透率
combo(T, ["1月", "2月", "3月", "4月", "5月", "6月"], "销量",
      [12, 18, 25, 31, 38, 42], "渗透率", [32, 38, 44, 49, 53, 55],
      柱单位="万辆", 线单位="%", 宽=15, 高=6, 输出=os.path.join(S, "g4.png"))
# G5 table：季度销量
bar(T, {"Q1": 28, "Q2": 36, "Q3": 42, "Q4": 48}, 强调="Q4", 横向=False,
    单位="万辆", 宽=15, 高=6, 输出=os.path.join(S, "g5.png"))
# G6 annotated：年度销量 + 目标线 + CAGR
line(T, ["2019", "2020", "2021", "2022", "2023", "2024", "2025", "2026"],
     {"年销量": [18, 25, 38, 55, 72, 90, 105, 122]}, 单位="万辆",
     标注=[{"类型": "目标线", "值": 100, "文": "2025目标 100万"},
           {"类型": "cagr", "文": "CAGR 34%"}],
     宽=15, 高=6, 输出=os.path.join(S, "g6.png"))
# G7 dashboard：月度趋势
line(T, ["1月", "2月", "3月", "4月", "5月", "6月"],
     {"销量": [12, 18, 25, 31, 38, 42]}, 单位="万辆", 宽=12, 高=5,
     输出=os.path.join(S, "g7.png"))
# G8 dumbbell：保值率
dumbbell(T, {"SUV": (52, 64), "轿车": (48, 60), "MPV": (45, 55), "跑车": (40, 47)},
         前名="2023款", 后名="2026款", 单位="%", 宽=15, 高=6,
         输出=os.path.join(S, "g8.png"))
# G9 ranked：品牌排名
bar(T, {"领跑": 58, "追风": 46, "极光": 38, "星驰": 30, "云帆": 22, "其他": 18},
    强调="领跑", 单位="万辆", 输出=os.path.join(S, "g9.png"))
# G11 dualpanel：左绝对值 + 右占比
bar(T, {"纯电": 88, "混动": 42, "燃油": 24}, 强调="纯电", 横向=False,
    单位="万辆", 输出=os.path.join(S, "g11a.png"))
pie(T, {"纯电": 58, "混动": 27, "燃油": 15}, 输出=os.path.join(S, "g11b.png"))
# G12 bullet：4 KPI
bullet_rows(T, [
    {"名": "年销量", "实际": 122, "目标": 120, "区间": [(80, "差"), (100, "中"), (130, "优")]},
    {"名": "渗透率", "实际": 55, "目标": 50, "区间": [(30, "差"), (45, "中"), (60, "优")]},
    {"名": "市占率", "实际": 18, "目标": 15, "区间": [(8, "差"), (12, "中"), (20, "优")]},
    {"名": "NPS", "实际": 62, "目标": 60, "区间": [(40, "差"), (55, "中"), (70, "优")]},
], 输出=os.path.join(S, "g12.png"))
# G13 pareto：客诉
pareto(T, {"续航虚标": 42, "充电慢": 28, "车机卡顿": 15, "异响": 9, "其他": 6},
       单位="起", 宽=15, 高=6, 输出=os.path.join(S, "g13.png"))
# G14 stacked：季度动力结构
stacked(T, ["Q1", "Q2", "Q3", "Q4"],
        {"纯电": [12, 18, 25, 32], "混动": [8, 10, 12, 14], "燃油": [18, 14, 10, 8]},
        单位="万辆", 宽=15, 高=6, 输出=os.path.join(S, "g14.png"))
print("charts done")
